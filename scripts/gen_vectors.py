#!/usr/bin/env python3
"""Golden vectors for the Sumo Frog program's pure maths, computed in Python.

Usage: python3 scripts/gen_vectors.py   (writes tests/vectors/golden.json)

Python is the spec. `programs/sumofrog/src/lib.rs` has a unit test
(`golden_vectors`) that loads the JSON and checks the Rust functions give the
same answers, so an AI (or a human) can't quietly change the maths.

Each retarget vector carries two answers:
  expected        what the Rust code does today (i64 wrap/saturate included)
  intent          the plain-maths rule from the doc comment, with no i64 limits
They only differ for settings no real deployment would use (retarget_interval *
target_block_time > i64::MAX / 4 seconds, ~73 billion years), which `initialize`
now rejects (MAX_RETARGET_WINDOW). Those vectors are marked `intent_differs: true`
and the generator lists them when it runs.
"""
import hashlib
import json
import os
import struct

U64_MAX = 2**64 - 1
I64_MAX = 2**63 - 1
I64_MIN = -(2**63)
MAX_ADJUST = 4
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "vectors", "golden.json")


# ---------- helpers that copy Rust integer semantics ----------
def as_i64(x):
    """`x as i64` for a u64: two's-complement wrap."""
    x &= U64_MAX
    return x - 2**64 if x > I64_MAX else x


def sat_i64(x):
    return max(I64_MIN, min(I64_MAX, x))


def rust_div(a, b):
    """Rust integer division truncates toward zero."""
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b >= 0) else -q


# ---------- the spec ----------
def sha256(*parts):
    h = hashlib.sha256()
    for p in parts:
        h.update(p)
    return h.digest()


def le_u64(n):
    return struct.pack("<Q", n)


def le_i64(n):
    return struct.pack("<q", n)


def work_value(h):
    """First 8 bytes of the hash, big-endian. Lower = more work."""
    return int.from_bytes(h[:8], "big")


def pow_hash(challenge, miner, nonce):
    return sha256(challenge, miner, le_u64(nonce))


def next_challenge(sol_hash, slot, blocks_mined_after):
    return sha256(sol_hash, le_u64(slot), le_u64(blocks_mined_after))


def genesis_challenge(mint, slot, unix_ts):
    return sha256(b"sumo frog genesis", mint, le_u64(slot), le_i64(unix_ts))


def block_reward(initial, halving_interval, blocks_mined):
    era = blocks_mined // halving_interval
    return 0 if era >= 64 else initial >> era


def retarget_rust(old, elapsed, interval, block_time):
    # u128 product, capped to [1, i64::MAX] (no wrap since 31 Oct 2026; before, a huge
    # interval wrapped negative when cast to i64).
    expected = min(max(interval * max(block_time, 0), 1), I64_MAX)
    lo = max(rust_div(expected, MAX_ADJUST), 1)
    hi = sat_i64(expected * MAX_ADJUST)
    actual = min(max(elapsed, lo), hi)  # Rust clamp; lo <= hi always holds here
    assert lo <= hi
    new = old * actual // expected
    return min(max(new, 1), U64_MAX)


def retarget_intent(old, elapsed, interval, block_time):
    expected = max(interval * block_time, 1)
    actual = min(max(elapsed, max(expected // MAX_ADJUST, 1)), expected * MAX_ADJUST)
    return min(max(old * actual // expected, 1), U64_MAX)


# ---------- vector sets ----------
def b(seed):
    return sha256(b"sumo-vector", seed.encode())


def build():
    v = {"_note": "Generated by scripts/gen_vectors.py. Do not edit by hand. u64/i64 values are strings."}

    hashes = [bytes(32), b"\xff" * 32, bytes(7) + b"\x01" + b"\xff" * 24,
              b"\x80" + bytes(31), b("wv1"), b("wv2")]
    v["work_value"] = [{"hash": h.hex(), "expected": str(work_value(h))} for h in hashes]

    v["pow_hash"] = []
    for i, nonce in enumerate([0, 1, 255, 256, 2**32, I64_MAX, U64_MAX]):
        c, m = b(f"challenge{i}"), b(f"miner{i}")
        h = pow_hash(c, m, nonce)
        v["pow_hash"].append({"challenge": c.hex(), "miner": m.hex(), "nonce": str(nonce),
                              "hash": h.hex(), "work_value": str(work_value(h))})

    v["next_challenge"] = []
    for i, (slot, bm) in enumerate([(0, 1), (1, 1), (123_456_789, 42), (U64_MAX, U64_MAX)]):
        h = b(f"solution{i}")
        v["next_challenge"].append({"solution_hash": h.hex(), "slot": str(slot), "blocks_mined": str(bm),
                                    "expected": next_challenge(h, slot, bm).hex()})

    v["genesis_challenge"] = []
    for i, (slot, ts) in enumerate([(0, 0), (987_654, 1_793_362_084), (U64_MAX, -1), (1, I64_MIN)]):
        m = b(f"mint{i}")
        v["genesis_challenge"].append({"mint": m.hex(), "slot": str(slot), "unix_ts": str(ts),
                                       "expected": genesis_challenge(m, slot, ts).hex()})

    R = 50 * 10**9
    br = [(R, 210_000, 0), (R, 210_000, 209_999), (R, 210_000, 210_000), (R, 210_000, 420_000),
          (R, 210_000, 210_000 * 33 - 1), (R, 210_000, 210_000 * 33),  # 50e9 >> 33 = 5, >> 36 = 0
          (R, 210_000, 210_000 * 36), (R, 210_000, 210_000 * 63), (R, 210_000, 210_000 * 64),
          (R, 6, 5), (R, 6, 6), (R, 6, 12),
          (U64_MAX, 1, 0), (U64_MAX, 1, 63), (U64_MAX, 1, 64), (U64_MAX, 1, U64_MAX),
          (1, 1, 0), (1, 1, 1), (R, U64_MAX, U64_MAX - 1), (R, U64_MAX, U64_MAX)]
    v["block_reward"] = [{"initial": str(i), "halving_interval": str(h), "blocks_mined": str(n),
                          "expected": str(block_reward(i, h, n))} for i, h, n in br]

    T = 1 << 36  # live network starts at 28 bits = 2^36 target
    rt = [
        (T, 600, 10, 60), (T, 300, 10, 60), (T, 1200, 10, 60),        # on time, 2x fast, 2x slow
        (T, 150, 10, 60), (T, 149, 10, 60), (T, 2400, 10, 60), (T, 2401, 10, 60),  # clamp edges
        (T, 0, 10, 60), (T, -5, 10, 60), (T, I64_MIN, 10, 60),        # elapsed = 0 / negative
        (T, I64_MAX, 10, 60),                                         # huge elapsed -> 4x easier
        (1000, 599, 10, 60),                                          # rounding down
        (1, 0, 10, 60), (1, 1, 1, 1), (3, 0, 1, 1),                   # never below 1
        (U64_MAX, I64_MAX, 10, 60), (U64_MAX, 600, 10, 60), (U64_MAX // 2, 2400, 10, 60),  # cap at u64::MAX
        (T, 1, 1, 1), (T, 3, 1, 3), (T, 0, 1, 3),                     # tiny expected (expected/4 rounds to 0 -> 1)
        (T, I64_MAX, I64_MAX, 1), (T, I64_MAX // 4, I64_MAX, 1),      # expected = i64::MAX, *4 saturates
        (T, I64_MAX, 2**40, 2**30),                                   # interval*block_time saturates
        (T, I64_MAX, 2**63, 1), (T, 600, U64_MAX, 1),                 # interval > i64::MAX (used to wrap negative)
        (T, 600, 2**63 + 10, 1), (U64_MAX, 0, U64_MAX, 2**62),        # more huge-interval cases
        (T, I64_MAX // 4, I64_MAX // 4, 1), (T, 0, I64_MAX // 4, 1),  # largest window initialize accepts
        (T, I64_MAX, I64_MAX // 4, 1), (U64_MAX, I64_MAX, I64_MAX // 4, 1),
    ]
    v["retarget"] = []
    for old, el, iv, bt in rt:
        e, i = retarget_rust(old, el, iv, bt), retarget_intent(old, el, iv, bt)
        v["retarget"].append({"old": str(old), "elapsed": str(el), "interval": str(iv), "block_time": str(bt),
                              "expected": str(e), "intent": str(i), "intent_differs": e != i})
    return v


if __name__ == "__main__":
    v = build()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(v, f, indent=1)
        f.write("\n")
    n = sum(len(x) for k, x in v.items() if isinstance(x, list))
    print(f"wrote {n} vectors to {os.path.relpath(OUT, ROOT)}")
    for r in v["retarget"]:
        if r["intent_differs"]:
            print(f"  note: Rust differs from plain maths for retarget(old={r['old']}, elapsed={r['elapsed']}, "
                  f"interval={r['interval']}, block_time={r['block_time']}): rust={r['expected']} maths={r['intent']}")
